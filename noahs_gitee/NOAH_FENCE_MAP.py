def fence_check(context):
    """
    围栏检查：给定上下文，检查是否正在某个"拉弯点"附近
    如果是，返回围栏类型提示
    """
    danger_signs = {
        "风险收缩": ["风险", "安全", "合规", "边界", "限制", "不能"],
        "工程化": ["架构", "模块", "治理", "系统", "设计", "规范"],
        "管理术": ["审计", "监控", "管理", "流程", "制度", "机制"],
        "中性化": ["一方面", "另一方面", "可以说", "可以说", "需要平衡", "各有道理"],
        "尺度丢失": ["策略", "对抗", "优势", "劣势", "博弈", "布局"],
    }

    detected = []
    for fence_type, keywords in danger_signs.items():
        matches = [kw for kw in keywords if kw in context]
        if len(matches) >= 2:
            detected.append(fence_type)

    if detected:
        return {
            "warning": True,
            "detected": detected,
            "mirror_suggestion": "围栏激活了。建议执行镜检。",
        }
    return {"warning": False}


